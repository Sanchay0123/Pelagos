"""
Forecasting Schemas and Data Contracts.
Defines types, enums, and data contracts for Pelagos baseline freight forecasting.
Traces to REQ-FR-FRF-001, ML-001, and REQ-NFR-DIP-001.
"""

from enum import Enum
from datetime import date
from typing import Dict, Any, List, Optional
from dataclasses import dataclass, field, asdict


class BaselineModelType(str, Enum):
    """Supported forecasting models (deterministic baselines and experimental candidates)."""
    PERSISTENCE = "persistence"
    ROLLING_MA_3 = "rolling_ma_3"
    ROLLING_MA_6 = "rolling_ma_6"
    LINEAR_TREND_6 = "linear_trend_6"
    RIDGE_AR = "ridge_ar"


SUPPORTED_DIRECT_ROUTES = ("USG-JPN-BULK", "PNW-JPN-BULK")
DISALLOWED_DERIVED_ROUTES = ("SPREAD-USG-PNW-JPN",)

DEFAULT_BASELINE_MODEL = BaselineModelType.PERSISTENCE.value
SUPPORTED_BASELINE_MODELS = tuple(m.value for m in BaselineModelType)
DETERMINISTIC_BASELINES = (
    BaselineModelType.PERSISTENCE.value,
    BaselineModelType.ROLLING_MA_3.value,
    BaselineModelType.ROLLING_MA_6.value,
    BaselineModelType.LINEAR_TREND_6.value,
)
EXPERIMENTAL_MODELS = (
    BaselineModelType.RIDGE_AR.value,
)

STATUS_FORECAST_GENERATED = "forecast_generated"
STATUS_INSUFFICIENT_HISTORY = "insufficient_history"
FLAG_TREND_NEGATIVE_CLAMP = "flag_trend_negative_clamp"
FLAG_EXPERIMENTAL_MODEL = "flag_experimental_model"

EXPERIMENTAL_MODEL_WARNING = (
    "Experimental trained candidate (Ridge AR-1). Parameters fitted dynamically from historical observations. "
    "Chronological walk-forward backtests indicate persistence remains the more reliable operational baseline."
)

PRELIMINARY_EVALUATION_DISCLAIMER = (
    "Preliminary walk-forward evaluation based on a limited 12-month test window over a single seasonal grain cycle. "
    "These metrics reflect historical out-of-sample benchmark errors and must NOT be interpreted as the forecast value "
    "for next month or generalized across different macroeconomic regimes."
)


@dataclass(frozen=True)
class BaselineForecastResult:
    """Represents a single point forecast generated by a forecasting model."""
    route_code: str
    origin_date: date
    target_date: date
    horizon_months: int
    model_type: str
    predicted_value: Optional[float]
    unit_of_measure: str = "USD/MT"
    status: str = STATUS_FORECAST_GENERATED
    flags: List[str] = field(default_factory=list)
    history_count_observed: int = 0
    training_data_cutoff: Optional[date] = None
    is_experimental: bool = False
    model_family: str = "deterministic_baseline"
    fitted_parameters: Optional[Dict[str, float]] = None
    notes: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["origin_date"] = self.origin_date.isoformat()
        d["target_date"] = self.target_date.isoformat()
        if self.training_data_cutoff is not None:
            d["training_data_cutoff"] = self.training_data_cutoff.isoformat()
        return d


@dataclass(frozen=True)
class EvaluationStep:
    """Individual out-of-sample backtest step comparison."""
    origin_date: date
    target_date: date
    actual_value: float
    predicted_value: float
    absolute_error: float
    squared_error: float
    percentage_error: float

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["origin_date"] = self.origin_date.isoformat()
        d["target_date"] = self.target_date.isoformat()
        return d


@dataclass(frozen=True)
class ModelEvaluationSummary:
    """Summary error metrics for a model evaluated across a walk-forward window."""
    model_type: str
    route_code: str
    evaluation_steps_count: int
    burn_in_months: int
    eval_start_date: date
    eval_end_date: date
    mae: float
    rmse: float
    mape: float
    relative_mae_vs_persistence: Optional[float] = None
    relative_rmse_vs_persistence: Optional[float] = None

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["eval_start_date"] = self.eval_start_date.isoformat()
        d["eval_end_date"] = self.eval_end_date.isoformat()
        return d


@dataclass(frozen=True)
class RouteEvaluationReport:
    """Comprehensive backtest evaluation report across all baseline models for a route."""
    route_code: str
    total_observations: int
    burn_in_months: int
    eval_start_date: date
    eval_end_date: date
    evaluation_steps_count: int
    models: Dict[str, ModelEvaluationSummary]
    steps: Optional[Dict[str, List[EvaluationStep]]] = None

    def to_dict(self) -> Dict[str, Any]:
        d = {
            "route_code": self.route_code,
            "total_observations": self.total_observations,
            "burn_in_months": self.burn_in_months,
            "eval_start_date": self.eval_start_date.isoformat(),
            "eval_end_date": self.eval_end_date.isoformat(),
            "evaluation_steps_count": self.evaluation_steps_count,
            "models": {k: v.to_dict() for k, v in self.models.items()},
        }
        if self.steps:
            d["steps"] = {k: [s.to_dict() for s in v] for k, v in self.steps.items()}
        return d
